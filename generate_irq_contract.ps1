param(
    [ValidateSet('Boot','App')][string]$Mode = 'Boot',
    [string]$AppProject = (Join-Path $PSScriptRoot '..\RL78_F13_Boot_loader_CAN_app'),
    [switch]$CheckOnly
)
$ErrorActionPreference = 'Stop'
$utf8 = New-Object System.Text.UTF8Encoding($false)
$config = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'can_boot_config.h'))
function Macro([string]$name) {
    $m = [regex]::Match($config, '#define\s+'+$name+'\s+\((0x[0-9A-Fa-f]+|[0-9]+)[UL]*\)')
    if (!$m.Success) { throw "Missing contract macro $name" }
    return [Convert]::ToUInt32($m.Groups[1].Value.Replace('0x',''), $(if($m.Groups[1].Value.StartsWith('0x')){16}else{10}))
}
function Generated([string]$path,[string]$value) {
    $value = $value.Replace("`r`n","`n").Replace("`n","`r`n")
    if ($CheckOnly) {
        if (!(Test-Path -LiteralPath $path) -or [IO.File]::ReadAllText($path) -cne $value) { throw "Stale generated IRQ contract: $path" }
    } elseif (!(Test-Path -LiteralPath $path) -or [IO.File]::ReadAllText($path) -cne $value) {
        [IO.File]::WriteAllText($path,$value,$utf8)
    }
}
$start = Macro 'CAN_BOOT_APPLICATION_START'
if ($start -ne 0x2000) { throw 'This IRQ ABI requires the F13 app table at 0x2000.' }
if ((Macro 'CAN_BOOT_RAM_OWNER_OFFSET') -ne 0 -or (Macro 'CAN_BOOT_SHARED_RAM_ADDRESS') -ne 0xFF710) {
    throw 'This IRQ ABI requires the owner byte at 0xFF710.'
}
if ($Mode -eq 'Boot') {
    $text = "; Generated by generate_irq_contract.ps1 -Mode Boot. Do not edit.`n"
    $text += "; Complete normal-vector ownership; no dependency on app handler names.`n"
    $text += ".EXTERN _f13_boot_timer_isr`n.SECTION .text, TEXT`n"
    for ($v=4; $v -le 0x7C; $v+=2) {
        $text += ('f13_irq_{0:X2} .VECTOR 0x{0:X2}' -f $v)+"`n"
        $text += ('f13_irq_{0:X2}:' -f $v)+"`n    CALL !f13_irq_dispatch`n"
        $text += ('    .DB 0x{0:X2}' -f $v)+"`n"
    }
    # CALL pushes four bytes. Three PUSH words put its low PC at SP+6.
    # RET consumes only that synthetic CALL frame, never the hardware IRQ frame.
    $text += @'
; Preserve AX/HL/ES, with IE still disabled. BC/DE/CS are untouched.
; The literal is a byte: no unaligned ROM word access is required.
f13_irq_dispatch:
    PUSH AX
    PUSH HL
    MOV A,ES
    PUSH AX
    MOV ES,#0
    MOVW AX,[SP+6]
    MOVW HL,AX
    MOV A,ES:[HL]
    MOV X,A
    MOV A,#0
    SHLW AX,1
'@  # AX is little-endian X(low), A(high).
    $text += "`n"+('    ADDW AX,#0x{0:X4}' -f $start)+"`n"
    $text += ('    CMP !0x{0:X4},#0x{1:X2}' -f ((Macro 'CAN_BOOT_SHARED_RAM_ADDRESS') -band 0xFFFF),(Macro 'CAN_BOOT_RAM_OWNER_APPLICATION'))+"`n"
    $text += "    BZ `$f13_irq_target`n"
    $text += ('    CMP !0x{0:X4},#0x{1:X2}' -f ((Macro 'CAN_BOOT_SHARED_RAM_ADDRESS') -band 0xFFFF),(Macro 'CAN_BOOT_RAM_OWNER_BOOT'))+"`n"
    $text += "    BNZ `$f13_irq_default`n"
    $text += ('    CMPW AX,#0x{0:X4}' -f ($start+0x1E*2))+"`n"
    $text += @'
    BNZ $f13_irq_default
    MOVW AX,#LOWW(_f13_boot_timer_isr)
    BR $f13_irq_target
f13_irq_default:
    MOVW AX,#LOWW(f13_boot_default_isr)
f13_irq_target:
    MOVW [SP+6],AX
    POP AX
    MOV ES,A
    POP HL
    POP AX
    RET
f13_boot_default_isr:
    RETI
; Reset remains in cstart. Reserved 0x02 and debugger BRK 0x7E are not routed.
'@
    Generated (Join-Path $PSScriptRoot 'f13_boot_vectors.asm') ($text+"`n")
} else {
    $AppProject = (Resolve-Path -LiteralPath $AppProject).Path
    $handlers = [IO.File]::ReadAllText((Join-Path $AppProject 'app_irq_handlers.json')) | ConvertFrom-Json
    $map = @{}
    foreach ($p in $handlers.PSObject.Properties) {
        if ($p.Name -notmatch '^0x[0-9A-Fa-f]{2}$') { throw "Invalid vector key: $($p.Name)" }
        $v = [Convert]::ToInt32($p.Name.Substring(2),16)
        if ($v -lt 4 -or $v -gt 0x62 -or ($v -band 1)) { throw "Reserved/non-normal F13 vector: $($p.Name)" }
        if ($map.ContainsKey($v) -or $p.Value -notmatch '^[A-Za-z_][A-Za-z0-9_]*$') { throw "Invalid/duplicate handler: $($p.Name)" }
        $map[$v] = [string]$p.Value
    }
    $text = "; Generated from this app's app_irq_handlers.json. Do not edit.`n.EXTERN _start`n"
    $projects = @(Get-ChildItem -LiteralPath $AppProject -Filter '*.mtpj')
    if ($projects.Count -ne 1) { throw 'Exactly one app MTPJ is required.' }
    [xml]$project = [IO.File]::ReadAllText($projects[0].FullName)
    $sources = @($project.SelectNodes('//Instance[Type="File"]') | Where-Object { $_.RelativePath -match '\.c$' } | ForEach-Object {
        $path = [string]$_.RelativePath
        if (![IO.Path]::IsPathRooted($path)) { $path = Join-Path $AppProject $path }
        [IO.File]::ReadAllText($path)
    })
    foreach ($symbol in $map.Values) {
        $declarations = @($sources | Where-Object { $_ -match ('(?m)^\s*#pragma\s+interrupt\s+'+[regex]::Escape($symbol)+'\s*\r?$') })
        if ($declarations.Count -ne 1) { throw "Handler $symbol requires one normal interrupt pragma without vect in registered sources." }
    }
    foreach ($symbol in @($map.Values | Sort-Object -Unique)) { $text += ".EXTERN _$symbol`n" }
    $text += ".jtext .CSEG AT FLASH_TABLE`n    BR !!_start ; RESET 0x00`n    .DB4 0xFFFFFFFF ; Reserved 0x02`n"
    for ($v=4; $v -le 0x7C; $v+=2) {
        $symbol = if ($map.ContainsKey($v)) {'_'+$map[$v]} else {'f13_app_default_isr'}
        $text += ('    BR !!{0} ; vector 0x{1:X2}, slot 0x{2:X4}' -f $symbol,$v,($start+$v*2))+"`n"
    }
    $text += @'
    BR !!f13_app_default_brk ; Reserved BRK slot 0x7E; not physically forwarded
.SECTION .text, TEXT
f13_app_default_isr:
    RETI
f13_app_default_brk:
    RETB
'@
    Generated (Join-Path $AppProject 'app_irq_table.inc') ($text+"`n")
    $table = [IO.File]::ReadAllText((Join-Path $AppProject 'ftable.inc'))
    $identity = "/* Generated from this app's ftable.inc. Do not edit. */`n#ifndef F13_APP_IDENTITY_H`n#define F13_APP_IDENTITY_H`n"
    foreach ($field in @('VERSION','BUILD')) {
        $m = [regex]::Match($table, '(?m)^APP_IMAGE_'+$field+'\s+\.EQU\s+(0x[0-9A-Fa-f]+|[0-9]+)')
        if (!$m.Success) { throw "Missing app-local APP_IMAGE_$field" }
        $identity += '#define CAN_BOOT_APP_FIRMWARE_'+$field+' ('+$m.Groups[1].Value+"UL)`n"
    }
    Generated (Join-Path $AppProject 'app_identity.h') ($identity+"#endif`n")
}
Write-Host "F13 $Mode IRQ contract $(if($CheckOnly){'verified'}else{'prepared'})."
